namespace DemaConsulting.Plexus.Scene;

/// <summary>
///     Horizontal alignment of text inside its layout rectangle.
/// </summary>
public enum TextAlignment
{
    /// <summary>Text starts at the left edge of the rectangle.</summary>
    Left,

    /// <summary>Text is centered horizontally in the rectangle.</summary>
    Center,

    /// <summary>Text ends at the right edge of the rectangle.</summary>
    Right,
}
